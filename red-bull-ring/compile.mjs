import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {compileTrack} from './compile-track.mjs';
import {addTerrain} from './terrain.mjs';
import {auditDriving,auditPitConnections} from './audit-driving.mjs';
const here=path.dirname(fileURLToPath(import.meta.url)),read=name=>JSON.parse(fs.readFileSync(path.join(here,'source',name)));
const track=compileTrack(read('red-bull-ring-reference.json'),read('red-bull-ring-features.json'),read('ground-reference.json'));
const plan=addTerrain(track,read('ground-reference.json'));
plan.meta.drivingAudit=auditDriving(plan);
if(plan.meta.drivingAudit.uncovered)throw Error('The driving corridor contains gaps: '+JSON.stringify(plan.meta.drivingAudit));
plan.meta.pitConnections=auditPitConnections(plan);
if(Object.values(plan.meta.pitConnections).some(end=>end.uncovered||end.maxSurfaceStepStuds>.01))throw Error('The pit entry or exit does not meet the racing surface: '+JSON.stringify(plan.meta.pitConnections));
fs.writeFileSync(path.join(here,'red-bull-ring-plan.json'),JSON.stringify(plan));
fs.writeFileSync(path.join(here,'generation-report.json'),JSON.stringify(plan.meta,null,2)+'\n');
console.log(JSON.stringify({parts:plan.parts.length,totalWithGrass:plan.parts.length+1,groups:plan.meta.groupCounts,terrain:{bulk:plan.meta.terrain.bulkParts,edges:plan.meta.terrain.edgeParts,edgeLowering:plan.meta.terrain.edgeLowering,bulkDressing:plan.meta.terrain.bulkDressing},elevationChange:plan.meta.retainedHeightRange[1]-plan.meta.retainedHeightRange[0]},null,2));
